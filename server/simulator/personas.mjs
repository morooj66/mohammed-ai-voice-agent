export const DEFAULT_CALLER = 'khalid';
export function getPersona(id = DEFAULT_CALLER) {
  const persona = PERSONAS[id];
  if (!persona) throw Error(`unknown_caller:${id}`);
  return persona;
}
export function parseCallerArg(argv) {
  const value = argv.find((a) => a.startsWith('--caller='))?.split('=')[1];
  return getPersona(value || DEFAULT_CALLER);
}
export function callerConfig(env, persona) {
  return { agentId: env[persona.env.agent], versionId: env[persona.env.version], voiceId: env[persona.env.voice], voiceApproved: env[persona.env.voiceApproved] === 'true',
    voiceAccessVerified: persona.env.voiceAccessVerified ? env[persona.env.voiceAccessVerified] === 'true' : persona.voiceAccessVerified === true,
    mohammedVersionId: env[persona.mohammed.version], mohammedHash: env[persona.mohammed.hash] };
}

// Local configuration checks (no network). Remote checks (published prompt, text-only, auth) run in the recorder.
export function callerConfigProblems(env, persona, { go = false } = {}) {
  const c = callerConfig(env, persona), name = persona.id, problems = [];
  if (env.KHALID_BRAIN !== 'elevenlabs_agent' || !c.agentId) problems.push(`${name}: agent not configured (${persona.env.agent})`);
  if (!c.versionId) problems.push(`${name}: ${persona.env.version} not set (pin an audited version)`);
  if (!c.voiceId) problems.push(`${name}: ${persona.env.voice} not set`);
  if (go && persona.env.voiceAccessVerified && !c.voiceAccessVerified) problems.push(`${name}: ${persona.env.voiceAccessVerified} is not true`);
  if (!persona.approvedVoiceId) problems.push(`${name}: candidate ${persona.candidateVoiceName || 'voice'} (${persona.candidateVoiceId || 'unknown'}) is pending My Voices verification and owner approval`);
  else if (c.voiceId !== persona.approvedVoiceId) problems.push(`${name}: voice is not the approved voice`);
  if (go && !c.voiceApproved) problems.push(`${name}: ${persona.env.voiceApproved} is not true`);
  if (!c.mohammedVersionId || !c.mohammedHash) problems.push(`${name}: Mohammed pin for this scenario not set (${persona.mohammed.version} / ${persona.mohammed.hash})`);
  if (c.agentId && c.agentId === env.ELEVENLABS_AGENT_ID) problems.push(`${name}: caller agent equals Mohammed agent`);
  for (const other of Object.values(PERSONAS)) {
    if (other.id !== persona.id && c.agentId && c.agentId === env[other.env.agent]) problems.push(`${name}: agent shared with ${other.id} (scenarios must be independent)`);
  }
  return problems;
}
