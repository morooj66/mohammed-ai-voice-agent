// Converts a (preferably edited) recording into the «شاهد المحاكاة» player fixture. OFFLINE only.
//
// DRAFT (default): preview/draft-public/recordings/<id>.{wav,json}, served only by the local preview
//   dev server (never built or deployed). Open: http://127.0.0.1:<port>/?draft=<id>
// APPROVED (public page): requires the owner's explicit review AND
//   RECORDING_REVIEW_APPROVED=true node scripts/build-simulation-fixture.mjs <edited.json> --approve
//   -> public/recordings/<id>.wav + src/lib/approved-recording.js
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateRecordingFixture } from '../src/lib/recording-fixture.js';
import { CALLERS } from '../src/lib/callers.js';
import { recordingVersionProblems } from '../server/simulator/version-check.mjs';

// The caller comes from the recording's own metadata (recordings made before personas existed are Khalid's).
export function callerOf(meta) {
  const id = meta.caller?.id || 'khalid';
  const caller = CALLERS.find((c) => c.id === id);
  if (!caller) throw Error(`unknown_caller:${id}`);
  return caller;
}

// Recordings rejected by the owner: technical testing only, never a public fixture.
export const REJECTED_RECORDINGS = Object.freeze([
  'khalid-mohammed-2026-10-10T16-45-02-835Z', 'khalid-mohammed-2026-10-10T17-19-58-967Z',
  'khalid-mohammed-2026-10-10T17-29-35-374Z', 'khalid-mohammed-2026-10-10T19-06-30-048Z',
]);
// Updates ONLY the given caller's entry; every other caller's approved recording is kept as-is.
export function approvedModuleSource(current, callerId, fixture) {
  const next = Object.fromEntries(CALLERS.map((c) => [c.id, current?.[c.id] ?? null]));
  for (const [id, f] of Object.entries(next)) if (id !== callerId && f && (f.id === fixture.id || f.audioSrc === fixture.audioSrc)) throw Error(`refused: fixture collides with ${id}'s recording`);
  next[callerId] = fixture;
  return `// GENERATED by scripts/build-simulation-fixture.mjs --approve after owner review. Do not edit by hand.\n// One independent entry per caller.\nexport const approvedRecordings = Object.freeze(${JSON.stringify(next, null, 2)});\n`;
}
export const isRejected = (name) => REJECTED_RECORDINGS.some((r) => String(name).startsWith(r));

export function buildFixture(meta, { id, approved, verifiedAt = new Date().toISOString() }) {
  const caller = callerOf(meta);
  const sourceName = meta.edit?.source ? basename(meta.edit.source, '.json') : basename(meta.audioFile || '', '.wav');
  const edited = Boolean(meta.edit);
  const removed = edited && (meta.edit.droppedLineIds?.length || 0);
  const editNote = !edited ? '' : removed
    ? ` نسخة محرّرة: قُصّرت الفواصل الصامتة وحُذف ${removed} من المقاطع للاختصار، دون تغيير أي جملة.`
    : ' نسخة محرّرة: قُصّرت الفواصل الصامتة فقط، دون تغيير أي جملة.';
  const fixture = {
    id, draft: !approved, label: approved ? 'محادثة آلية حقيقية' : 'تسجيل تجريبي غير معتمد', kind: 'recording',
    audioSrc: `/recordings/${id}.wav`, duration: meta.duration, consentConfirmed: true,
    verifiedAt: approved ? verifiedAt : 'UNAPPROVED-DRAFT',
    caller: { id: caller.id, nameAr: caller.nameAr },
    provenance: `محادثة آلية حقيقية بين وكيلين (محمد: وكيل التأمين، ${caller.nameAr}: عميل افتراضي) — بيانات وهمية.${editNote}`,
    source: { recording: sourceName, complete: meta.edit ? meta.edit.sourceComplete : meta.complete === true, edit: meta.edit || null, agents: meta.agents || null, versionCheck: meta.versionCheck || null },
    transcript: meta.transcript.map((c) => ({ id: c.id, speaker: c.speaker, text: c.text, start: c.start, end: c.end })),
  };
  if (!validateRecordingFixture(fixture)) throw Error('fixture_invalid (timing, speakers, text or duration)');
  const versionProblems = recordingVersionProblems(meta);
  if (approved && versionProblems.length) throw Error(`refused_invalid_recording: ${versionProblems.join('; ')}`);
  // A mismatched version is marked INVALID (may be listened to locally, never approved or exported).
  if (meta.versionCheck && versionProblems.length) Object.assign(fixture, { invalid: true, label: 'تسجيل غير صالح — نسخة محمد لا تطابق المطلوبة', provenance: `تسجيل غير صالح: ${versionProblems[0]}. ${fixture.provenance}` });
  return { fixture, sourceName };
}

async function main(argv) {
  const input = argv.find((a) => !a.startsWith('--'));
  const approve = argv.includes('--approve');
  if (!input) { console.log('Usage: node scripts/build-simulation-fixture.mjs recordings-raw/edited/<name>.json [--approve]'); process.exitCode = 2; return; }
  const metaPath = resolve(input), meta = JSON.parse(readFileSync(metaPath, 'utf8'));
  const caller = callerOf(meta);
  const stamp = basename(metaPath, '.json').replace(/^(khalid|raj)-mohammed-/, '');
  // Khalid ids keep their previous format; other callers carry their id so files never collide.
  const id = `${approve ? 'sim' : 'draft'}-${caller.id === 'khalid' ? '' : `${caller.id}-`}${stamp}`;
  const { fixture, sourceName } = buildFixture(meta, { id, approved: approve });
  if (approve) {
    const problems = [];
    if (process.env.RECORDING_REVIEW_APPROVED !== 'true') problems.push('RECORDING_REVIEW_APPROVED is not true (owner review required)');
    if (isRejected(sourceName)) problems.push(`source ${sourceName} was rejected: technical testing only`);
    if (fixture.source.complete !== true) problems.push('source recording did not end naturally (complete=false)');
    problems.push(...recordingVersionProblems(meta));
    if (problems.length) { console.log('REFUSED:\n- ' + problems.join('\n- ')); process.exitCode = 3; return; }
  }
  const root = fileURLToPath(new URL('../', import.meta.url));
  const audioDir = approve ? join(root, 'public/recordings') : join(root, 'preview/draft-public/recordings');
  mkdirSync(audioDir, { recursive: true });
  copyFileSync(join(dirname(metaPath), meta.audioFile), join(audioDir, `${id}.wav`));
  if (approve) {
    const { approvedRecordings: current } = await import(`${new URL('../src/lib/approved-recording.js', import.meta.url).href}?t=${Date.now()}`);
    writeFileSync(join(root, 'src/lib/approved-recording.js'), approvedModuleSource(current, caller.id, fixture));
    console.log(`APPROVED fixture written: public/recordings/${id}.wav + src/lib/approved-recording.js (${fixture.duration}s, ${fixture.transcript.length} lines)`);
  } else {
    writeFileSync(join(audioDir, `${id}.json`), JSON.stringify(fixture, null, 2) + '\n');
    console.log(`DRAFT fixture written (local preview only): preview/draft-public/recordings/${id}.{wav,json} (${fixture.duration}s, ${fixture.transcript.length} lines) · open the preview with ?draft=${id}`);
  }
}

if (fileURLToPath(import.meta.url) === process.argv[1]) {
  main(process.argv.slice(2)).catch((e) => { console.error('FAILED:', e.message); process.exitCode = 1; });
}
