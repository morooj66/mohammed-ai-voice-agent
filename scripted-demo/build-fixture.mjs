// Turns the scripted-demo mix into a player fixture (offline; uses the built-in macOS `afconvert` for AAC).
//   node scripted-demo/build-fixture.mjs [--scratch]     DRAFT -> preview/draft-public/recordings/ (local preview only)
//   SCRIPTED_DEMO_APPROVED=true node scripted-demo/build-fixture.mjs --approve
//                                                        APPROVED -> public/recordings/ + src/lib/scripted-demo.js
// A SCRATCH mix (stand-in voices) can only ever become a local draft.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { validateRecordingFixture } from '../src/lib/recording-fixture.js';

const root = new URL('../', import.meta.url), P = (p) => fileURLToPath(new URL(p, root));
export const PROVENANCE = 'محاكاة صوتية لسيناريو مكتوب بأصوات وكيلَي المشروع (محمد وخالد) — ليست تسجيلًا لمكالمة آلية مباشرة. أصوات الشارع ومركز الاتصال مضافة من مكتبة Mixkit المرخّصة. المشروع تجربة شخصية مستقلة غير تابعة لنجم أو لأي شركة تأمين.';

export function scriptedFixture(meta, { id, approved, scratch = false, verifiedAt = new Date().toISOString() }) {
  if (scratch && approved) throw Error('scratch_mix_can_never_be_approved');
  const fixture = { id, kind: 'scripted', draft: !approved, scratch: scratch || undefined,
    label: approved ? 'محاكاة صوتية مكتوبة' : scratch ? 'مزج تجريبي بأصوات مؤقتة' : 'محاكاة مكتوبة — مسودة',
    audioSrc: `/recordings/${id}.m4a`, duration: meta.duration, consentConfirmed: true, verifiedAt: approved ? verifiedAt : 'UNAPPROVED-DRAFT',
    caller: { id: 'khalid', nameAr: 'خالد' },
    provenance: scratch ? `مزج تجريبي للبيئتين الصوتيتين بأصوات مؤقتة من تسجيل سابق — ليس الحوار المعتمد ولا يُنشر. ${PROVENANCE}` : PROVENANCE,
    transcript: meta.cues };
  if (!validateRecordingFixture(fixture)) throw Error('scripted_fixture_invalid');
  return fixture;
}

if (fileURLToPath(import.meta.url) === process.argv[1]) {
  const scratch = process.argv.includes('--scratch'), approve = process.argv.includes('--approve');
  const VERSION = (process.argv.find((a) => a.startsWith('--version=')) || '--version=v1').split('=')[1];
  if (approve && process.env.SCRIPTED_DEMO_APPROVED !== 'true') throw Error('requires_SCRIPTED_DEMO_APPROVED_true');
  const name = scratch ? 'SCRATCH-environment-check' : `khalid-mohammed-scripted-${VERSION}`, src = P(`production/scripted-demo/out/${name}`);
  if (!existsSync(`${src}.wav`)) throw Error(`missing_mix_${name}`);
  const meta = JSON.parse(readFileSync(`${src}.json`, 'utf8'));
  if (!scratch && meta.kind !== 'scripted') throw Error('final_mix_required');
  const id = approve ? `scripted-khalid-mohammed-${VERSION}` : scratch ? 'draft-scripted-scratch' : `draft-scripted-${VERSION}`;
  if (!approve && !scratch && VERSION === 'v1' && existsSync(P('preview/draft-public/recordings/draft-scripted-v1.m4a')) && !process.argv.includes('--allow-v1-rebuild')) throw Error('v1_draft_is_locked');
  const fixture = scriptedFixture(meta, { id, approved: approve, scratch });
  const dir = P(approve ? 'public/recordings/' : 'preview/draft-public/recordings/'); mkdirSync(dir, { recursive: true });
  execFileSync('afconvert', ['-f', 'm4af', '-d', 'aac', '-b', '192000', `${src}.wav`, `${dir}${id}.m4a`]);
  if (approve) writeFileSync(P('src/lib/scripted-demo.js'), `// GENERATED by scripted-demo/build-fixture.mjs --approve after owner review. Do not edit by hand.\nexport const scriptedDemo = Object.freeze(${JSON.stringify(fixture, null, 2)});\n`);
  else writeFileSync(`${dir}${id}.json`, JSON.stringify(fixture, null, 2) + '\n');
  console.log(`${approve ? 'APPROVED' : 'DRAFT'} scripted fixture: ${id}.m4a (${fixture.duration}s, ${fixture.transcript.length} lines)${approve ? '' : ` · preview: ?draft=${id}`}`);
}
